class ClimateStation:
    def __init__(self, city, temperature, humidity, rainfall):
        self.city = city
        self.temperature = temperature
        self.humidity = humidity
        self.rainfall = rainfall

    def display_summary(self):
        print(f"Station: {self.city} | Temp: {self.temperature}°C | Humidity: {self.humidity}% | Rainfall: {self.rainfall}mm")

    def calculate_risk(self):
        if self.temperature >= 40:
            return "EXTREME"
        elif self.temperature >= 35 or self.rainfall < 5:
            return "HIGH"
        elif self.temperature >= 30 or self.rainfall < 15:
            return "MODERATE"
        else:
            return "LOW"

    def update_temperature(self, new_temperature):
        self.temperature = new_temperature
        print(f"Updated temperature for {self.city} to {self.temperature}°C")

    def recommendation(self):
        risk = self.calculate_risk()
        if risk == "LOW":
            return "Normal monitoring"
        elif risk == "MODERATE":
            return "Continue monitoring"
        elif risk == "HIGH":
            return "Increased monitoring recommended"
        elif risk == "EXTREME":
            return "Immediate attention required"

print("\n=== PART 3: OOP Stations Implementation ===")
s1 = ClimateStation("Damascus", 38.5, 20, 10.0)
s2 = ClimateStation("Aleppo", 40.2, 15, 8.5)
s3 = ClimateStation("Latakia", 31.0, 75, 12.5)
s4 = ClimateStation("Homs", 36.0, 35, 2.0)
s5 = ClimateStation("Daraa", 29.0, 40, 10.0)

