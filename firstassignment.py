def calculate_risk(temperature, rainfall):
    if temperature >= 40:
        return "EXTREME"
    elif temperature >= 35 or rainfall < 5:
        return "HIGH"
    elif temperature >= 30 or rainfall < 15:
        return "MODERATE"
    else:
        return "LOW"

print("\n=== PART 2: Risk Observation ===")
for record in climate_data:
    station = record["station"]
    temp = record["temperature"]
    rainfall = record["rainfall"]
    if temp is None:
        continue
    risk = calculate_risk(temp, rainfall)
    print(f"Station {station} | Temp: {temp}°C | Risk: {risk}")

def get_stats(temp_list):
    avg = sum(temp_list) / len(temp_list)
    max_val = max(temp_list)
    min_val = min(temp_list)
    return (avg, min_val, max_val)

valid_temps = []
valid_cities = []

for record in climate_data:
    temp = record["temperature"]
    if temp is None:
        continue
    valid_temps.append(temp)
    valid_cities.append(record)

stats = get_stats(valid_temps)

