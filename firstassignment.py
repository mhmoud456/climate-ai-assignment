for station in stations_list:
    station.display_summary()
    risk = station.calculate_risk()
    rec = station.recommendation()
    print(f"  -> Risk Level: {risk} | Action: {rec}\n")

print("=== Updating Temperature Example ===")
s5.update_temperature(33.5)
s5.display_summary()

