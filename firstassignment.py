climate_data = [
    {"station": "Damascus", "temperature": 38.5, "rainfall": 10.0, "humidity": 20},
    {"station": "Aleppo", "temperature": 40.2, "rainfall": 8.5, "humidity": 15},
    {"station": "Latakia", "temperature": 31.0, "rainfall": 12.5, "humidity": 75},
    {"station": "Homs", "temperature": 36.0, "rainfall": 2.0, "humidity": 35},
    {"station": "Deir ez-Zor", "temperature": None, "rainfall": 0.0, "humidity": 10}
]

print("=== PART 1: Climate Data Summary ===")
total_temp = 0
valid = 0
high = float('-inf')
low = float('inf')
high_temp_station = ""
low_temp_station = ""
classifications = {}

for record in climate_data:
    station = record["station"]
    temp = record["temperature"]

    if temp is None:
        print(f"Skipping station {station} due to missing temperature data.")
        continue

    valid += 1
    total_temp += temp

    if temp > high:
        high = temp
        high_temp_station = station

    if temp < low:
        low = temp
        low_temp_station = station

    print(f"Station: {station} | Temp: {temp}°C | Rainfall: {record['rainfall']}mm | Humidity: {record['humidity']}%")

    if temp >= 40.0:
        category = "Extreme Heat"
    elif temp >= 35.0:
        category = "High Heat"
    elif temp >= 30.0:
        category = "Moderate Heat"
    else:
        category = "Normal"

    print(f"The temperature in {station} is {category}.")
    classifications[station] = category

avg_temp = total_temp / valid
print(f"\nValid observations: {valid}")
print(f"Average Temperature across all stations: {avg_temp:.2f}°C")
print(f"Highest Temperature: {high}°C in {high_temp_station}")
print(f"Lowest Temperature: {low}°C in {low_temp_station}")
print("Final Classifications Dictionary:")
print(classifications)


